# 5. 函数定义与返回
# ============================================================

def calc_return(close_list, n):
    """
    计算某只股票 n 日涨跌幅
    参数:
        close_list: list[float]  收盘价序列，按时间升序
        n: int                   回看天数
    返回:
        float  涨跌幅（如 0.05 表示涨 5%）
        None   数据不足时返回 None
    """
    if len(close_list) < n + 1:
        print(f"⚠️ 数据不足：需要至少 {n+1} 个交易日，实际只有 {len(close_list)} 个")
        return None
    return (close_list[-1] - close_list[-n-1]) / close_list[-n-1]


# 测试 calc_return
test_prices = [10.0, 10.2, 10.5, 10.3, 10.8, 11.0, 10.9, 11.2]
print("\n=== 测试 calc_return ===")
print(f"数据: {test_prices}")
r5 = calc_return(test_prices, 5)
print(f"5日涨跌幅: {r5:.4f}（{r5*100:.2f}%）")

r20 = calc_return(test_prices, 20)  # 数据不够
print(f"20日涨跌幅: {r20}")  # 应返回 None

